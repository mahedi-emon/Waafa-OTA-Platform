function airport(
  iata: string,
  city: string,
  name: string,
  country: string,
  countryCode: string,
  pinnedRank?: number,
): Airport {
  return pinnedRank === undefined
    ? { iata, city, name, country, countryCode }
    : { iata, city, name, country, countryCode, pinnedRank };
}

