const url = (code) => `https://pics.avs.io/al_square/96/96/${code}@2x.png`;
const sha = (buffer) => createHash("sha256").update(buffer).digest("hex");

async function get(code) {
  const response = await fetch(url(code), { signal: AbortSignal.timeout(15_000) });
  if (!response.ok) throw new Error(`${code}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

const wanted = process.argv.slice(2).map((code) => code.toUpperCase());
const codes = wanted.length > 0 ? wanted : CODES;
await mkdir(outDir, { recursive: true });
const placeholder = sha(await get("ZZ"));

const missing = [];
for (const code of codes) {
  if (!/^[A-Z0-9]{2}$/.test(code)) {
    missing.push(code);
    continue;
  }
  const image = await get(code);
  if (sha(image) === placeholder) {
    missing.push(code);
    continue;
  }
  await writeFile(join(outDir, `${code}.png`), image);
}

const bundled = (await readdir(outDir))
  .filter((file) => /^[A-Z0-9]{2}\.png$/.test(file))
  .map((file) => file.slice(0, 2))
  .sort();
await writeFile(
  listFile,
  `// Generated by scripts/fetch-airline-logos.mjs: airlines with a bundled logo in /media/airlines.\n` +
    `export const AIRLINE_LOGO_CODES: ReadonlySet<string> = new Set(\n  "${bundled.join(" ")}".split(" "),\n);\n`,
);
